type SpecInput = [key: string, label: string, value: string, extra?: Pick<Spec, 'num' | 'better' | 'glossaryKey'>];

function product(
  id: string,
  name: string,
  category: CategoryId,
  type: string,
  art: ArtKind,
  rupees: number,
  stock: number,
  summary: string,
  description: string,
  features: string[],
  specs: SpecInput[],
): Product {
  const full = specs.map(([key, label, value, extra]) => ({ key, label, value, ...extra }));
  return {
    id,
    name,
    brand: name.split(' ')[0]!,
    category,
    type,
    art,
    priceCents: rupees * 100,
    currency: 'INR',
    stock,
    summary,
    description,
    features,
    specs: full,
    images: [`/products/${id}.svg`],
    glossaryKeys: full.flatMap((s) => (s.glossaryKey ? [s.glossaryKey] : [])),
    ratingSummary: { count: 0, average: 0 },
    sample: true,
  };
}

const hi = (num: number, glossaryKey?: string) => ({ num, better: 'higher' as const, ...(glossaryKey && { glossaryKey }) });
const lo = (num: number, glossaryKey?: string) => ({ num, better: 'lower' as const, ...(glossaryKey && { glossaryKey }) });
const g = (glossaryKey: string) => ({ glossaryKey });


// Shared AI types. No Firebase imports here, so policy and prompts stay pure and testable.

export type FeatureId =
  | 'spec_explain' // F1
  | 'fit_check' // F2
  | 'fit_general' // F2 without the profile
  | 'compare' // F3
  | 'review_digest' // F4
  | 'smart_search' // F6
  | 'ask' // F7
  | 'order_help' // F8
  | 'review_screen'; // F9

export const FEATURE_NAMES: Record<FeatureId, string> = {
  spec_explain: 'Spec explanation',
  fit_check: 'Fit check',
  fit_general: 'General suitability',
  compare: 'Comparison',
  review_digest: 'Review summary',
  smart_search: 'Search wording',
  ask: 'Conversation',
  order_help: 'Order help',
  review_screen: 'Review screening',
};

/**
 * public    – catalogue facts only
 * user_text – text typed or written by a person, which may contain personal details
 * personal  – profile, fit requirements or order context: never leaves the device
 */
export type DataClass = 'public' | 'user_text' | 'personal';

export interface SentField {
  label: string;
  cls: DataClass;
}

export type SchemaName = 'fit' | 'compare' | 'digest' | 'search' | 'screen';

export interface ChatTurn {
  role: 'user' | 'model';
  text: string;
}

export interface PromptSpec {
  feature: FeatureId;
  /** The most sensitive class among the fields. */
  dataClass: DataClass;
  prompt: string;
  /** Generated by the prompt builder from what it actually put in the prompt. */
  fields: SentField[];
  /** Short description for the ledger. */
  subject: string;
  schema?: SchemaName;
  /** Conversation only. */
  chat?: { system: string; history: ChatTurn[] };
  /** Features with no on-device path (multi-turn chat). */
  cloudOnly?: boolean;
}

export type RequestedMode = 'only_on_device' | 'prefer_on_device' | 'only_in_cloud';
export type MadeBy = 'on_device' | 'in_cloud';
export type LocalStatus = 'unsupported' | 'unavailable' | 'downloadable' | 'downloading' | 'available';

export interface Receipt {
  /** Reported by the SDK on the response. */
  madeBy: MadeBy;
  requestedMode: RequestedMode;
  sent: string[];
}

export type LedgerOutcome = 'answered' | 'declined' | 'unavailable' | 'failed' | 'rejected_output';

export interface LedgerEntry {
  id: string;
  atMs: number;
  feature: FeatureId;
  subject: string;
  requestedMode: RequestedMode | null;
  madeBy: MadeBy | null;
  outcome: LedgerOutcome;
  /** True when a request to the cloud was actually attempted. */
  cloudAttempted: boolean;
  /** Field labels from the prompt builder. For on-device runs these stayed on the device. */
  fields: string[];
}

export type RunResult<T> =
  | { status: 'ok'; data: T; receipt: Receipt }
  | { status: 'declined' }
  | { status: 'unavailable'; reason: string }
  | { status: 'failed'; message: string }
  | { status: 'invalid' };
